// Package mediafs は、登録済みのメディアフォルダとその内側のファイルへの
// アクセスを、ファイルシステムで確かめる担当である。
//
// 任意のファイルを読み出されないための規則 ——登録フォルダの内側にあり、
// symlink を辿った先も内側にあり、通常ファイルであること—— をここ1か所で
// 持つ。配信・既定アプリで開く機能・メディアフォルダの登録・ディレクトリ
// 選択は、それぞれが宣言した interface 越しにこのパッケージを使う。
// パスの包含の判定そのものはファイルシステムに触れない純粋関数として
// internal/domain にあり、ここは Lstat・EvalSymlinks・Open などの外部 I/O と
// それらの組み立てだけを持つ。
//
// 依存してよいのは internal/domain だけで、他の internal/* は参照しない。
// 依存の向きは ARCHITECTURE.md を参照。
package mediafs

// FS はメディアフォルダとその内側のファイルへのアクセスである。状態を
// 持たないので、ゼロ値のまま使える。
type FS struct{}

// New はメディアフォルダとその内側のファイルへのアクセスを返す。
func New() FS { return FS{} }
